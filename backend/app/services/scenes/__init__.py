"""场景编排：自然语言 → 场景定义 → 能力映射 → 冲突检测 → 执行。

| 模块 | 职责 |
|---|---|
| `models.py` | 数据结构：场景步骤、编排结果、执行结果 |
| `intents.py` | 场景意图模板（读 `config/scene_intents.yaml`） |
| `planner.py` | **编排器**：能力校验 → 重复检测 → 意图约束 → 产出可执行计划 |
| `executor.py` | **执行器**：低风险执行、高风险待确认、失败重试与降级 |
| `nl.py` | 自然语言 → 候选动作序列（唯一用到 LLM 的地方） |

一条贯穿的设计原则
------------------
**LLM 只负责"想做什么"，不负责"能不能做"。**
它产出的是**候选**动作，之后每一步都要过 `planner` 的确定性校验：

- 设备存不存在？→ 查设备目录
- 有没有这个可写能力？→ 查能力档案
- 值在不在范围内？→ 查能力档案的 min/max 与枚举
- 是否与场景意图矛盾？→ 查意图模板
- 是否自相矛盾（同一能力被设两次）？→ 重复检测

这样"模型说错话"最多导致**动作被剔除**，不会变成**对设备下发非法指令**。
"""


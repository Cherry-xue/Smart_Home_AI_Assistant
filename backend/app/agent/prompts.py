def build_agent_prompt(agent: str) -> str:
    """拼出一个专业 Agent 的完整系统提示词。"""
    body = _AGENT_BODIES.get(agent)
    if body is None:
        raise KeyError(f"未知的 Agent 标识：{agent!r}；可选：{sorted(_AGENT_BODIES)}")
    return f"{body.strip()}\n\n---\n\n{COMMON_SAFETY}"


